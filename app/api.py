from flask import Blueprint
from flask_restx import Api

from app.auth.routes import ns as auth_ns
from app.core.errors import register_error_handlers
from app.urls.routes import ns as urls_ns
from app.urls.routes_v1 import ns as urls_v1_ns

api_bp = Blueprint("api", __name__, url_prefix="/api")

API_DESCRIPTION = """
Shorten long URLs and redirect short codes to the original URL.

**Authentication.** Endpoints marked with a lock use HTTP Basic authentication:
create an account with `POST /api/v1/auth/register/`, then use **Authorize**.

**Error format.** Every error response has the same JSON shape:
`{"error": {"code": "...", "message": "...", "details": [...]}}`.
`details` is present only for validation and conflict errors. Any endpoint can
also return `500 internal_server_error` if something unexpected goes wrong.

**Specification.** Generated by Flask-RESTX, which produces Swagger 2.0
(OpenAPI 2), not OpenAPI 3.0.
"""

api = Api(
    api_bp,
    title="URL Shortener API",
    version="1.0",
    description=API_DESCRIPTION,
    doc="/docs",
    # Adds the Authorize button; protected operations reference "basicAuth".
    authorizations={"basicAuth": {"type": "basic"}},
)
api.add_namespace(urls_ns)
api.add_namespace(auth_ns)
api.add_namespace(urls_v1_ns)
register_error_handlers(api)
